def calculate_texture_features(face):
    """
    Calculate basic texture statistics from a face crop.
    """

    gray = cv2.cvtColor(face, cv2.COLOR_BGR2GRAY)

    mean_intensity = float(np.mean(gray))
    std_intensity = float(np.std(gray))

    # Local variation
    laplacian = cv2.Laplacian(gray, cv2.CV_64F)
    laplacian_variance = float(laplacian.var())

    return {
        "mean_intensity": mean_intensity,
        "std_intensity": std_intensity,
        "laplacian_variance": laplacian_variance
    }

# ============================================
# Edge Density
# ============================================

def calculate_edge_density(face):
    """
    Calculate the proportion of pixels
    that belong to detected edges.
    """

    gray = cv2.cvtColor(face, cv2.COLOR_BGR2GRAY)

    edges = cv2.Canny(gray, 100, 200)

    edge_pixels = np.count_nonzero(edges)
    total_pixels = edges.size

    edge_density = edge_pixels / total_pixels

    return float(edge_density)

# ============================================
# Noise Estimation
# ============================================

def calculate_noise_features(face):
    """
    Estimate local high-frequency noise
    using a Gaussian-blur residual.
    """

    gray = cv2.cvtColor(face, cv2.COLOR_BGR2GRAY)

    blurred = cv2.GaussianBlur(
        gray,
        (5, 5),
        0
    )

    residual = gray.astype(np.float32) - blurred.astype(np.float32)

    noise_std = float(np.std(residual))
    noise_mean = float(np.mean(np.abs(residual)))

    return {
        "noise_std": noise_std,
        "noise_mean": noise_mean
    }

