    # Inner boundary
    # --------------------------------------------------------

    rw = min(
        ring_width,
        max(2, w // 10),
        max(2, h // 10)
    )

    inner_top = face[:rw, :]
    inner_bottom = face[-rw:, :]
    inner_left = face[:, :rw]
    inner_right = face[:, -rw:]

