def generate_anomaly_heatmap(face):
    """
    Generate a lightweight visual anomaly map using:
    - local high-frequency response
    - local noise/residual
    - edge response

    Returns:
        heatmap: normalized 0-1 map
    """

    gray = cv2.cvtColor(
        face,
        cv2.COLOR_BGR2GRAY
    ).astype(np.float32)

    # --------------------------------------------------------
    # 1. High-frequency / Laplacian response
    # --------------------------------------------------------

    laplacian = cv2.Laplacian(
        gray,
        cv2.CV_32F
    )

    laplacian_abs = np.abs(laplacian)

    # --------------------------------------------------------
    # 2. Local noise residual
    # --------------------------------------------------------

    blurred = cv2.GaussianBlur(
        gray,
        (5, 5),
        0
    )

    residual = np.abs(
        gray - blurred
    )

    # --------------------------------------------------------
    # 3. Edge response
    # --------------------------------------------------------

    edges = cv2.Canny(
        gray.astype(np.uint8),
        60,
        150
    ).astype(np.float32) / 255.0

    # --------------------------------------------------------
    # Normalize each feature map
    # --------------------------------------------------------

    def normalize_map(data):

        min_val = np.percentile(data, 5)
        max_val = np.percentile(data, 95)

        if max_val - min_val < 1e-6:
            return np.zeros_like(data)

        normalized = (
            data - min_val
        ) / (
            max_val - min_val
        )

        return np.clip(
            normalized,
            0,
            1
        )

    laplacian_map = normalize_map(
        laplacian_abs
    )

    noise_map = normalize_map(
        residual
    )

    edge_map = normalize_map(
        edges
    )

    # --------------------------------------------------------
    # Combined anomaly map
    # --------------------------------------------------------

    heatmap = (
        0.45 * laplacian_map +
        0.35 * noise_map +
        0.20 * edge_map
    )

    heatmap = cv2.GaussianBlur(
        heatmap,
        (7, 7),
        0
    )

    return np.clip(
        heatmap,
        0,
        1
    )

