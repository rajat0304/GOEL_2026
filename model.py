def detect_faces(image, min_confidence=0.5):
    """
    Detect faces using MediaPipe Face Detector.

    Returns:
        [
            {
                "bbox": (x, y, w, h),
                "confidence": confidence
            }
        ]
    """

    h, w = image.shape[:2]

    # OpenCV BGR -> RGB
    rgb_image = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2RGB
    )

    # NumPy -> MediaPipe Image
    mp_image = mp.Image(
        image_format=mp.ImageFormat.SRGB,
        data=rgb_image
    )

    # Run detector
    result = face_detector_mp.detect(mp_image)

    detected_faces = []

    for detection in result.detections:

        confidence = float(
            detection.categories[0].score
        )

        if confidence < min_confidence:
            continue

        bbox = detection.bounding_box

        x = int(bbox.origin_x)
        y = int(bbox.origin_y)

        box_w = int(bbox.width)
        box_h = int(bbox.height)

        # Clamp coordinates
        x = max(0, x)
        y = max(0, y)

        box_w = min(box_w, w - x)
        box_h = min(box_h, h - y)

        if box_w <= 0 or box_h <= 0:
            continue

        detected_faces.append({
            "bbox": (x, y, box_w, box_h),
            "confidence": confidence
        })

    return detected_faces

