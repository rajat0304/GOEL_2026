    """
    Analyze the immediate boundary around a detected face.

    Compares:
        1. Inner face boundary
        2. Outer background boundary

    Returns:
        boundary_score: 0-100
        evidence: measurable statistics
    """

    x, y, w, h = bbox

    H, W = image.shape[:2]

    # --------------------------------------------------------
    # Safety checks
    # --------------------------------------------------------

    if w <= 20 or h <= 20:
        return 0.0, {}

