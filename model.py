    # Face boundary coordinates
    # --------------------------------------------------------

    x1 = max(0, x)
    y1 = max(0, y)
    x2 = min(W, x + w)
    y2 = min(H, y + h)

    face = image[y1:y2, x1:x2]

    if face.size == 0:
        return 0.0, {}

